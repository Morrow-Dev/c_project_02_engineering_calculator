#include <string.h>
#include <stdio.h>
#include <stdbool.h>
#include "arithmetic.h"

double add(double a, double b) {
    double result = a+b;
    return result;
}

double subtract(double a, double b) {
    double result = a-b;
    return result;
}

double multiply(double a, double b) {
    double result = a*b;
    return result;
}

double divide(double a, double b) {
    double result = a/b;
    return result;
}